        [Test]
        public async Task WithUsings_CorrectString()
        {
            var compilationInfo = new CompilationInfo("MyCompilation1", targetNamespace: "Test.NS1")
                .AddNewClassInfo("MyClass1", AccessModifier.Public, ci =>
